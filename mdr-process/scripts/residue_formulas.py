#!/usr/bin/env python3
"""
Write mdr-process/src/residue_formulas.rs: the heavy-atom formula of each
chemical component in mdr-process/scripts/residue-codes.txt, from the PDB's
Chemical Component Dictionary (RCSB GraphQL, `chem_comps.formula`).

The composition check for a ligand declared by sequence (sequence.rs,
`expected_peptide_formula`) knows the 22 standard amino acids by heart; this
table is what lets it check the others (TPO, SEP, ASJ, ...; Travis 2026-10-02,
decision 4(b)). A code not in the table is still refused with a message.

To add codes: append them to residue-codes.txt (one per line), then
    python3 mdr-process/scripts/residue_formulas.py
and commit both files. Standard amino acids and nucleotides are skipped.
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
CODES = HERE / "residue-codes.txt"
OUT = HERE.parent / "src" / "residue_formulas.rs"
URL = "https://data.rcsb.org/graphql"
SKIP = set(
    "ALA ARG ASN ASP CYS GLN GLU GLY HIS ILE LEU LYS MET PHE PRO SER THR TRP "
    "TYR VAL SEC PYL DA DC DG DT DU A C G U".split()
)
QUERY = "query($ids:[String!]!){chem_comps(comp_ids:$ids){chem_comp{id formula type}}}"


def fetch(codes):
    out = []
    for i in range(0, len(codes), 100):
        body = json.dumps({"query": QUERY, "variables": {"ids": codes[i : i + 100]}})
        req = urllib.request.Request(
            URL, body.encode(), {"Content-Type": "application/json",
                                 "User-Agent": "mdrepo-rs residue_formulas.py"})
        out += json.load(urllib.request.urlopen(req, timeout=120))["data"]["chem_comps"]
    return {c["chem_comp"]["id"]: c["chem_comp"] for c in out if c}


def heavy(formula):
    atoms = {}
    for el, n in re.findall(r"([A-Z][a-z]?)(\d*)", formula):
        if el != "H":
            atoms[el.upper()] = atoms.get(el.upper(), 0) + int(n or 1)
    return sorted(atoms.items())


def main():
    codes = sorted({c.strip().upper() for c in CODES.read_text().split() if c.strip()} - SKIP)
    comps = fetch(codes)
    missing = [c for c in codes if c not in comps]
    if missing:
        sys.exit(f"not in the CCD: {' '.join(missing)}")
    lines = [
        "// Generated by mdr-process/scripts/residue_formulas.py from the PDB's",
        "// Chemical Component Dictionary; do not edit by hand. Add a code to",
        "// scripts/residue-codes.txt and rerun the script.",
        "",
        "/// Heavy atoms of a non-standard chemical component as a free molecule,",
        "/// by element (upper case, as `Formula` keys are), from the CCD",
        "pub fn component_heavy_atoms(code: &str) -> Option<&'static [(&'static str, u32)]> {",
        "    let atoms: &[(&str, u32)] = match code {",
    ]
    for code in codes:
        atoms = ", ".join(f'("{e}", {n})' for e, n in heavy(comps[code]["formula"]))
        lines.append(f'        // {comps[code]["type"]}: {comps[code]["formula"]}')
        lines.append(f'        "{code}" => &[{atoms}],')
    lines += ["        _ => return None,", "    };", "    Some(atoms)", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(codes)} codes -> {OUT}")


if __name__ == "__main__":
    main()
